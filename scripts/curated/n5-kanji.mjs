/** Learner readings for every N5 kanji. Anchors are words that use that reading. */

function r(type, kana, anchor, anchorReading, kunDisplay) {
  return { type, kana, anchor, anchorReading, kunDisplay: kunDisplay || "" };
}
function s(ja, en, reading) {
  return { ja, en, reading, flag: "" };
}

